func TestToZellijDirection(t *testing.T) {
	tests := []struct {
		input    domain.Direction
		expected string
	}{
		{domain.DirectionHorizontal, "vertical"},
		{domain.DirectionVertical, "horizontal"},
	}

	for _, tt := range tests {
		t.Run(string(tt.input), func(t *testing.T) {
			result := toZellijDirection(tt.input)
			assert.Equal(t, tt.expected, result)
		})
	}
}

func TestZellijGenerator_OutputIsValidKDL(t *testing.T) {
	gen := &ZellijGenerator{}
	session := createMultiWindowSession()
	output, err := gen.Generate(session)
	require.NoError(t, err)

	// Basic validation that output looks like valid KDL
	lines := strings.Split(output, "\n")

	// First non-comment line should open layout block
	assert.Contains(t, output, "layout {")

	// Should have matching braces
	openBraces := strings.Count(output, "{")
	closeBraces := strings.Count(output, "}")
	assert.Equal(t, openBraces, closeBraces, "unbalanced braces in output")

	// Should not have any unclosed quotes
	quoteCount := strings.Count(output, `"`)
	assert.Equal(t, 0, quoteCount%2, "unbalanced quotes in output")

	// First line should be a comment
	assert.True(t, strings.HasPrefix(lines[0], "//"), "first line should be a comment")
}

func TestZellijGenerator_NestedPanes(t *testing.T) {
	gen := &ZellijGenerator{}

	// Create a session with nested panes (vertical split containing horizontal splits)
	session := domain.Session{
		ID:                "session-nested",
		Name:              "nested",
		SessionName:       "proj_nested",
		WorkingDirectory:  "~/app",
		TargetMultiplexer: domain.MultiplexerZellij,
		DefaultWindowID:   "w1",
		Windows: []domain.Window{
			{
				ID:            "w1",
				Name:          "dev",
				RootDirection: domain.DirectionVertical,
				Panes: []domain.Pane{
					{
						ID:        "root",
						Size:      100,
						Direction: domain.DirectionVertical,
						Children: []domain.Pane{
							{
								ID:        "top",
								Size:      60,
								Direction: domain.DirectionHorizontal,
								Children: []domain.Pane{
									{ID: "p1", Name: "editor", Command: "nvim .", Size: 70},
									{ID: "p2", Name: "files", Command: "lf", Size: 30},
								},
							},
							{
								ID:      "p3",
								Name:    "terminal",
								Command: "",
								Size:    40,
							},
						},
					},
				},
			},
		},
	}

	output, err := gen.Generate(session)
	require.NoError(t, err)

	// Should contain nested split directions
	assert.Contains(t, output, `split_direction=`)

	// Should contain all pane names
	assert.Contains(t, output, `name "editor"`)
	assert.Contains(t, output, `name "files"`)
	assert.Contains(t, output, `name "terminal"`)
}
